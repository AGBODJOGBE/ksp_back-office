const QUOTE_STATUS: Record<QuoteStatus, { label: string; tone: BadgeTone }> = {
  draft: { label: 'Brouillon', tone: 'neutral' },
  sent: { label: 'Envoyé au client', tone: 'accent' },
  accepted: { label: 'Accepté', tone: 'success' },
  declined: { label: 'Décliné', tone: 'danger' },
  expired: { label: 'Expiré', tone: 'neutral' },
  superseded: { label: 'Remplacé par une révision', tone: 'neutral' },
  withdrawn: { label: 'Retiré', tone: 'neutral' },
};

export const quoteStatus = (status: QuoteStatus | string) =>
  (QUOTE_STATUS as Record<string, { label: string; tone: BadgeTone }>)[status] ?? {
    label: status,
    tone: 'neutral' as BadgeTone,
  };

